// Builds src/lib/chords/data.js from chords-db (MIT, https://github.com/tombatossals/chords-db).
// Usage: node scripts/build-chords.mjs path/to/chords-db/lib/guitar.json
// Each shape is packed into one string "FFFFFF NNNNNN base barres":
// frets per string low E → high e (x = muted, 0 = open, else fret relative to base, hex),
// fingers (0 = none), base fret, and barre frets joined by ',' ('-' when none).
import { readFileSync, writeFileSync } from 'node:fs'

const src = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const PC = { C: 0, Csharp: 1, D: 2, Eb: 3, E: 4, F: 5, Fsharp: 6, G: 7, Ab: 8, A: 9, Bb: 10, B: 11 }
const out = []
for (const [name, list] of Object.entries(src.chords)) {
  const bySuffix = {}
  for (const { suffix, positions } of list) {
    bySuffix[suffix] = positions.map((p) =>
      [
        p.frets.map((f) => (f < 0 ? 'x' : f.toString(16))).join(''),
        p.fingers.join(''),
        p.baseFret,
        p.barres.length ? p.barres.join(',') : '-',
      ].join(' '),
    )
  }
  out[PC[name]] = bySuffix
}
writeFileSync(
  new URL('../src/lib/chords/data.js', import.meta.url),
  '// Generated by scripts/build-chords.mjs from chords-db (MIT, see CHORDS-DB-LICENSE.txt). Do not edit.\n' +
    'export default ' + JSON.stringify(out) + '\n',
)
